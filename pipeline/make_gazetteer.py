def build_gazetteer(out_path: Path | None = None) -> Path:
    dest = out_path or (SITE_DIR / "assets" / "gazetteer.json")
    dest.parent.mkdir(parents=True, exist_ok=True)
    records = [
        {
            "name": name,
            "kind": kind,
            "sub": sub,
            "lat": lat,
            "lon": lon,
            "distance": dist,
            "aliases": aliases,
        }
        for name, kind, sub, lat, lon, dist, aliases in ENTRIES
    ]
    dest.write_text(json.dumps(records, separators=(",", ":"), ensure_ascii=False))
    return dest


